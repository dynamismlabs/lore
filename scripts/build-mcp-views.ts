/**
 * Bundles Lore's MCP view (`src/server/mcp/views/client`) into one HTML
 * document, written as a TypeScript string next to it. The string is
 * committed, so the Worker serves it with no build step or file read.
 * `views.test.ts` fails when it's stale.
 *
 *   pnpm mcp-views:build
 */
import { build } from 'esbuild';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const viewsDir = path.join(repo, 'src/server/mcp/views');
export const GENERATED_VIEW_FILE = path.join(viewsDir, 'lore-view.html.ts');

const HEADER =
  '// Generated by `pnpm mcp-views:build` from ./client. Edit the client, then rebuild. views.test.ts fails while this is stale.\n';

export async function renderLoreViewHtml(): Promise<string> {
  const bundle = await build({
    absWorkingDir: repo,
    entryPoints: [path.join(viewsDir, 'client/main.ts')],
    bundle: true,
    write: false,
    minify: true,
    platform: 'browser',
    format: 'iife',
    target: 'es2020',
    legalComments: 'none',
    tsconfig: path.join(repo, 'tsconfig.json'),
  });
  const script = bundle.outputFiles[0].text.trim().replace(/<\/script/gi, '<\\/script');
  const css = (await fs.readFile(path.join(viewsDir, 'client/styles.css'), 'utf8'))
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\s*\n\s*/g, '')
    .replace(/<\/style/gi, '<\\/style');
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Lore</title><style>${css}</style></head><body><main id="root"></main><script>${script}</script></body></html>`;
}

export async function renderGeneratedView(): Promise<string> {
  return `${HEADER}export const LORE_VIEW_HTML = ${JSON.stringify(await renderLoreViewHtml())};\n`;
}

async function main() {
  const source = await renderGeneratedView();
  await fs.writeFile(GENERATED_VIEW_FILE, source);
  console.log(
    `MCP view built: ${path.relative(repo, GENERATED_VIEW_FILE)} ${Math.round(Buffer.byteLength(source) / 1024)} KiB`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
